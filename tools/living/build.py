"""Builds PaleoDex data sets for living animals from the tables in this folder.

Each table module (e.g. primates.py) defines CLADES, UPGRADES and GENERA. For every genus it
writes one species entry (the genus's best-known species, mentioning the others) into
src/data/sets/living-<name>.ts, and its range today into tools/globe-data/ranges-spec.json.
Then run tools/globe-data/build_ranges.py to rebuild the range outlines.

Usage (from the project root):
    python3 -I tools/living/build.py primates
"""

import importlib.util
import json
import sys

HERE = __file__.rsplit('/', 1)[0]


def ts(v, indent=0):
    """A JSON value written as TypeScript (keys unquoted where safe, single quotes)."""
    pad = ' ' * indent
    if isinstance(v, (dict, list)) and not v:
        return '{}' if isinstance(v, dict) else '[]'
    if isinstance(v, dict):
        items = []
        for k, x in v.items():
            key = k if k.replace('_', 'a').isalnum() and not k[0].isdigit() else repr(k)
            items.append(f'{pad}  {key}: {ts(x, indent + 2)}')
        return '{\n' + ',\n'.join(items) + f',\n{pad}}}'
    if isinstance(v, list):
        if all(isinstance(x, str) for x in v) and sum(len(x) for x in v) < 80:
            return '[' + ', '.join(ts(x) for x in v) + ']'
        return '[\n' + ',\n'.join(f'{pad}  {ts(x, indent + 2)}' for x in v) + f',\n{pad}]'
    if isinstance(v, str):
        return "'" + v.replace('\\', '\\\\').replace("'", "\\'") + "'"
    return json.dumps(v)


def main():
    name = sys.argv[1]
    spec = importlib.util.spec_from_file_location(name, f'{HERE}/{name}.py')
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)

    species, ranges, missing = [], {}, []
    for g in mod.GENERA:
        entry = {
            'id': g['id'],
            'name': g['name'],
            'common': g['common'],
            'clade': g['clade'],
            'status': 'full',
            'ageText': g.get('age', 'Living today'),
            'placeText': g['place'],
            'formations': [],
            'summary': g['summary'],
            'facts': [{'label': k, 'value': v} for k, v in g['facts']],
            'keywords': g['keywords'],
        }
        species.append(entry)
        # Earlier phases come before today's range: either written out in the entry
        # ('pastRanges'), or from the module's HISTORIC table, where 'same' means the historic
        # range (about 1,000 to 150 years ago) was much as it is today.
        past = g.get('pastRanges', [])
        hist = getattr(mod, 'HISTORIC', {}).get(g['id'])
        if hist == 'same':
            past = [{'from': 1000, 'to': 150, 'label': 'Historic range (much as today)', 'sameAs': 1}]
        elif hist is not None:
            past = [{'from': 1000, 'to': 150, 'label': 'Historic range', 'regions': hist}]
        elif not past:
            missing.append(g['id'])
        today = {'from': 150 if past else g.get('rangeFrom', 10000), 'to': 0, 'label': 'Where it lives today', 'regions': g['range']}
        ranges[g['id']] = {'phases': [*past, today]}

    const = 'LIVING_' + name.upper().replace('-', '_')
    out = [
        f'// Living {name}: one entry per genus, its best-known species, with the others mentioned.',
        f'// Generated by tools/living/build.py from tools/living/{name}.py; edit that file, not this one.',
        '',
        "import type { DataSet } from '@/data/sets/types';",
        '',
        f'export const {const}: DataSet = {ts({"clades": mod.CLADES, "upgrades": mod.UPGRADES, "species": species})};',
        '',
    ]
    open(f'src/data/sets/living-{name}.ts', 'w').write('\n'.join(out))

    path = 'tools/globe-data/ranges-spec.json'
    allr = json.load(open(path))
    allr.update(ranges)
    json.dump(allr, open(path, 'w'), indent=2, ensure_ascii=False)
    if missing:
        print(f'No historic range yet for {len(missing)}: ' + ', '.join(missing))
    print(f'{len(species)} genera, {len(mod.CLADES)} new groups -> src/data/sets/living-{name}.ts; ranges added')


if __name__ == '__main__':
    main()
